create table medical_records (
    id bigint generated by default as identity primary key,
    patient_id bigint not null references patients (id),
    doctor_id bigint not null references doctors (id),
    appointment_id bigint unique references appointments (id),
    visit_at timestamp with time zone not null,
    chief_complaint varchar(500) not null,
    diagnosis varchar(1000) not null,
    notes varchar(2000),
    created_at timestamp with time zone not null,
    updated_at timestamp with time zone not null
);

create table medical_record_prescriptions (
    medical_record_id bigint not null references medical_records (id),
    line_order integer not null,
    medication varchar(120) not null,
    dosage varchar(80) not null,
    frequency varchar(80) not null,
    duration_days integer,
    instructions varchar(300),
    primary key (medical_record_id, line_order)
);

-- A patient's history is the primary read; a doctor's visit list is the
-- second. The unique appointment_id enforces one record per booked visit.
create index idx_medical_records_patient_visit on medical_records (patient_id, visit_at);
create index idx_medical_records_doctor_visit on medical_records (doctor_id, visit_at);
