create table invoices (
    id bigint generated by default as identity primary key,
    patient_id bigint not null references patients (id),
    appointment_id bigint unique references appointments (id),
    issued_at timestamp with time zone not null,
    notes varchar(1000),
    status varchar(20) not null default 'UNPAID',
    paid_at timestamp with time zone,
    created_at timestamp with time zone not null,
    updated_at timestamp with time zone not null
);

create table invoice_charge_items (
    invoice_id bigint not null references invoices (id),
    line_order integer not null,
    description varchar(200) not null,
    quantity integer not null,
    unit_price_cents bigint not null,
    primary key (invoice_id, line_order)
);

-- A patient's billing history is the primary read and the unpaid queue
-- the second; the unique appointment_id enforces one invoice per visit.
create index idx_invoices_patient_issued on invoices (patient_id, issued_at);
create index idx_invoices_status_issued on invoices (status, issued_at);
