create table appointments (
    id bigint generated by default as identity primary key,
    patient_id bigint not null references patients (id),
    doctor_id bigint not null references doctors (id),
    starts_at timestamp with time zone not null,
    duration_minutes integer not null,
    reason varchar(500),
    status varchar(20) not null default 'SCHEDULED',
    created_at timestamp with time zone not null,
    updated_at timestamp with time zone not null
);

-- Day views and the overlap check both read one doctor's appointments by
-- start time; the patient index serves a patient's visit history.
create index idx_appointments_doctor_start on appointments (doctor_id, starts_at);
create index idx_appointments_patient_start on appointments (patient_id, starts_at);
